package com.architek.oikos.architecture;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.net.URISyntaxException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashSet;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.junit.jupiter.api.Test;

import com.architek.oikos.accounting.domain.valueobject.AccountRole;

/**
 * Guards the shared chart of accounts, which is seeded twice on purpose and so
 * can drift. Same shape as {@link ReplyMediumSeedTest}, one catalog along.
 *
 * <p>V1__baseline.sql fills it for a real deployment; the dev profile cannot run
 * V1 (H2, Flyway disabled, schema generated by Hibernate) and loads
 * db/seed/seed_ledger_account.sql instead. Unlike the reply media, code does
 * branch on these rows: every posting that resolves its counterpart through a
 * global AccountRole fails with AccountRoleNotConfiguredException when the row is
 * missing. These accounts used to live only in a demo dataset, which is how a
 * deployment was one cleanup away from not being able to post a fund call.
 */
class LedgerAccountSeedTest {

    private static final Path RESOURCES = resolveModuleRoot().resolve("src/main/resources");
    private static final Path CATALOG_MIGRATION = RESOURCES.resolve("db/migration/V1__baseline.sql");
    private static final Path SEED = RESOURCES.resolve("db/seed/seed_ledger_account.sql");
    private static final Path DEV_PROFILE = RESOURCES.resolve("application-dev.yml");

    /** The global roles a posting looks up with findGlobalByRole - each must exist as a shared account. */
    private static final Set<String> GLOBAL_ROLES = Set.of(AccountRole.UNIT_ADVANCE.name(),
            AccountRole.SUPPLIER.name(), AccountRole.STAFF_PAYABLE.name(), AccountRole.DUES_INCOME.name());

    @Test
    void both_files_declare_the_same_accounts() throws IOException {
        assertThat(accountsIn(SEED))
                .as("db/seed/ re-seeds for dev what V1__baseline.sql seeds for prod - an account in one and not the "
                        + "other is a posting that works in one environment only")
                .containsExactlyInAnyOrderElementsOf(accountsIn(CATALOG_MIGRATION));
    }

    @Test
    void every_global_role_a_posting_resolves_is_seeded() throws IOException {
        assertThat(rolesIn(CATALOG_MIGRATION))
                .as("V1__baseline.sql must seed a shared account for every global AccountRole - without it the "
                        + "matching postings fail with AccountRoleNotConfiguredException")
                .containsAll(GLOBAL_ROLES);
    }

    @Test
    void the_dev_profile_loads_the_seed() throws IOException {
        assertThat(Files.readString(DEV_PROFILE))
                .as("application-dev.yml must list the seed file in spring.sql.init.data-locations")
                .contains(SEED.getFileName().toString());
    }

    @Test
    void the_seed_is_replayable() throws IOException {
        assertThat(Files.readString(SEED))
                .as("the dev seed runs on every start-up, so every insert must guard against its own row")
                .contains("WHERE NOT EXISTS");
    }

    /** The account number of every shared row a ledger_account insert declares, whichever form the file uses. */
    private static Set<String> accountsIn(Path file) throws IOException {
        return matchesIn(file, Pattern.compile("'[0-9a-f-]{36}',\\s*NULL,\\s*NULL,\\s*'(\\d{8})'"));
    }

    private static Set<String> rolesIn(Path file) throws IOException {
        return matchesIn(file, Pattern.compile("'[0-9a-f-]{36}',\\s*NULL,\\s*NULL,[^)]*?,\\s*(?:true|false),\\s*'([A-Z_]+)'"));
    }

    private static Set<String> matchesIn(Path file, Pattern pattern) throws IOException {
        Set<String> values = new LinkedHashSet<>();
        for (String statement : Files.readString(file).split(";")) {
            if (!statement.contains("INSERT INTO ledger_account")) {
                continue;
            }
            Matcher matcher = pattern.matcher(statement);
            while (matcher.find()) {
                values.add(matcher.group(1));
            }
        }
        if (values.isEmpty()) {
            throw new IllegalStateException("No shared ledger_account insert found in " + file.getFileName());
        }
        return values;
    }

    private static Path resolveModuleRoot() {
        try {
            Path testClasses = Path.of(
                    LedgerAccountSeedTest.class.getProtectionDomain().getCodeSource().getLocation().toURI());
            // testClasses points at <module-root>/target/test-classes
            return testClasses.getParent().getParent();
        } catch (URISyntaxException e) {
            throw new IllegalStateException("Could not resolve module root for SQL seed scan", e);
        }
    }
}
